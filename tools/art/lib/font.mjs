const GLYPHS = Object.fromEntries(
  Object.entries(G).map(([ch, rows]) => [ch, rows.split(" ").map((row) => [...row].map((bit) => bit === "1"))]),
);

export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function textWidth(text, scale = 1) {
  return text.length === 0 ? 0 : (text.length * (GLYPH_W + 1) - 1) * scale;
}

/** Draws `text` into `dst` at x, y (top-left), each font pixel `scale` px. */
export function drawText(dst, text, x, y, rgba, scale = 1) {
  let cx = x;
  for (const raw of text) {
    const glyph = GLYPHS[raw.toUpperCase()] ?? GLYPHS["?"];
    for (let gy = 0; gy < GLYPH_H; gy += 1)
      for (let gx = 0; gx < GLYPH_W; gx += 1) {
        if (!glyph[gy][gx]) continue;
        for (let sy = 0; sy < scale; sy += 1)
          for (let sx = 0; sx < scale; sx += 1) {
            const px = cx + gx * scale + sx;
            const py = y + gy * scale + sy;
            if (px >= 0 && py >= 0 && px < dst.width && py < dst.height) dst.data.set(rgba, (py * dst.width + px) * 4);
          }
      }
    cx += (GLYPH_W + 1) * scale;
  }
  return dst;
}

export function textRaster(text, rgba, scale = 1) {
  const out = blank(Math.max(1, textWidth(text, scale)), GLYPH_H * scale);
  return drawText(out, text, 0, 0, rgba, scale);
}
